-- 1. Enable Required Extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- Helper function for updating timestamps
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ==============================================================================
-- 2. CORE TABLES
-- ==============================================================================

-- TABLE: SHOPS
-- Stores laundry shops registered in the system
CREATE TABLE IF NOT EXISTS public.shops (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  shop_name VARCHAR(255) NOT NULL DEFAULT 'CleanOps Laundry Shop',
  address TEXT,
  contact_number VARCHAR(50),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- TABLE: USERS (Public User Profiles)
-- Mirrors Supabase Auth users and supports custom staff roles
CREATE TABLE IF NOT EXISTS public.users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email VARCHAR(255) UNIQUE,
  username VARCHAR(255),
  role VARCHAR(50) NOT NULL DEFAULT 'admin' CHECK (role IN ('admin', 'staff', 'supervisor')),
  phone_number VARCHAR(50),
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE SET NULL,
  work_schedule JSONB DEFAULT '["Mon", "Tue", "Wed", "Thu", "Fri"]'::jsonb,
  is_online INT DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- TABLE: CUSTOMERS
-- Registered customer directory
CREATE TABLE IF NOT EXISTS public.customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  fullname VARCHAR(255) NOT NULL,
  email VARCHAR(255),
  phone VARCHAR(50),
  address TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- TABLE: ORDERS
-- Core laundry orders / batches tracking
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number VARCHAR(100),
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL,
  customer_name VARCHAR(255) NOT NULL,
  category VARCHAR(100) DEFAULT 'Wash & Fold',
  total_amount NUMERIC(12, 2) DEFAULT 0.00,
  payment_status VARCHAR(50) NOT NULL DEFAULT 'Unpaid' CHECK (payment_status IN ('Paid', 'Unpaid')),
  payment_method VARCHAR(50) DEFAULT 'Cash',
  status VARCHAR(50) NOT NULL DEFAULT 'In Progress' CHECK (
    status IN ('Pending', 'Processing', 'In Progress', 'in Progress', 'Ready for Pickup', 'Completed', 'Cancelled', 'Canceled')
  ),
  order_source VARCHAR(50) DEFAULT 'walk-in',
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- TABLE: ORDER_ITEMS
-- Specific service loads within an order
CREATE TABLE IF NOT EXISTS public.order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  service_id BIGINT,
  item_name VARCHAR(255),
  quantity NUMERIC(10, 2) DEFAULT 1.0,
  price NUMERIC(12, 2) DEFAULT 0.00,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- TABLE: SERVICES
-- Available laundry services & price rates
CREATE TABLE IF NOT EXISTS public.services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  service_name VARCHAR(255) NOT NULL,
  category VARCHAR(100) DEFAULT 'Wash & Fold',
  price NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  turnaround_time VARCHAR(100) DEFAULT '24 Hours',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_promo BOOLEAN NOT NULL DEFAULT FALSE,
  promo_description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- TABLE: SERVICE_RECIPES
-- Ingredients / inventory deducted per kg of service
CREATE TABLE IF NOT EXISTS public.service_recipes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id BIGINT NOT NULL REFERENCES public.services(id) ON DELETE CASCADE,
  item_name VARCHAR(255) NOT NULL,
  quantity_per_kg NUMERIC(10, 3) NOT NULL DEFAULT 0.05,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- TABLE: INVENTORY
-- Detergents, softeners, packaging, and supplies
CREATE TABLE IF NOT EXISTS public.inventory (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  item_name VARCHAR(255) NOT NULL,
  category VARCHAR(100) DEFAULT 'Detergent',
  quantity NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  unit VARCHAR(50) NOT NULL DEFAULT 'kg',
  min_stock NUMERIC(12, 2) NOT NULL DEFAULT 10.00,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- TABLE: MACHINES
-- Washers and Dryers queue and schedule tracking
CREATE TABLE IF NOT EXISTS public.machines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  machine_name VARCHAR(100) NOT NULL,
  machine_type VARCHAR(50) NOT NULL DEFAULT 'Washer' CHECK (machine_type IN ('Washer', 'Dryer')),
  status VARCHAR(50) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available', 'In Operation', 'Under Maintenance')),
  current_customer VARCHAR(255) DEFAULT 'Idle - Ready for load',
  remaining_time VARCHAR(50) DEFAULT 'Ready',
  current_order_id BIGINT REFERENCES public.orders(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- TABLE: NOTIFICATIONS
-- System, booking, and inventory low-stock alerts
CREATE TABLE IF NOT EXISTS public.notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  unread BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- TABLE: CHAT_MESSAGES
-- Internal staff/client communication
CREATE TABLE IF NOT EXISTS public.chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
  sender_name VARCHAR(255) NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

