-- ==============================================================================
-- 4. AUTOMATIC AUTH SYNC (auth.users -> public.users & default shop)
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
  new_shop_id BIGINT;
BEGIN
  -- 1. Insert into public.users
  INSERT INTO public.users (id, email, username, role, is_online)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'username', split_part(NEW.email, '@', 1)),
    COALESCE(NEW.raw_user_meta_data->>'role', 'admin'),
    1
  )
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    username = EXCLUDED.username;

  -- 2. If the user is an admin, auto-create their laundry shop
  IF COALESCE(NEW.raw_user_meta_data->>'role', 'admin') = 'admin' THEN
    INSERT INTO public.shops (user_id, shop_name)
    VALUES (
      NEW.id,
      COALESCE(NEW.raw_user_meta_data->>'shop_name', 'CleanOps Laundry Shop')
    )
    RETURNING id INTO new_shop_id;

    -- Link the newly created shop to the user
    UPDATE public.users SET shop_id = new_shop_id WHERE id = NEW.id;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

